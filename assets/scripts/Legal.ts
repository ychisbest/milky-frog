// 按每行大致字数折行，再按行数分页。全角算 1，半角算 0.5。
export function paginate(text: string, cols: number, rows: number): string[] {
    const unit = (ch: string) => (ch.charCodeAt(0) <= 0xff ? 0.5 : 1);
    const lines: string[] = [];
    for (const para of text.split('\n')) {
        if (!para) { lines.push(''); continue; }
        let line = '';
        let width = 0;
        for (const ch of para) {
            const u = unit(ch);
            if (width + u > cols && line) {
                lines.push(line);
                line = ch;
                width = u;
            } else {
                line += ch;
                width += u;
            }
        }
        if (line) lines.push(line);
    }
    const pages: string[] = [];
    for (let i = 0; i < lines.length; i += rows) pages.push(lines.slice(i, i + rows).join('\n'));
    while (pages.length > 1 && !pages[pages.length - 1].trim()) pages.pop();
    return pages.length ? pages : [''];
}

